const DEFAULT_BADGES = ['Commonly Used'];

const MEDALLION_BY_ID = [
  { match: /bronze|select|where|order-by|distinct|limit-top|null-handling|cast-convert/i, layer: 'Bronze', stage: 'Ingestion Profiling' },
  { match: /join|cte|subquer|temp-table|view|case-when|exists|merge|row-number|rank|dense-rank|lag|lead|running|dedup|partitioning-logic|incremental|cdc|scd|watermark|late|audit|reconciliation|idempotent|duplicate/i, layer: 'Silver', stage: 'Transformation' },
  { match: /fact|dimension|star|surrogate|date-dimension|grain|aggregation-table|data-mart|group-by|having|union/i, layer: 'Gold', stage: 'Warehouse Serving' },
  { match: /index|partition-pruning|predicate|broadcast|query-plan|select-star|shuffle|optimization|dynamic/i, layer: 'Cross-Layer', stage: 'Performance Engineering' },
];

function inferLessonLayer(id, title) {
  const key = `${id} ${title}`;
  return MEDALLION_BY_ID.find(item => item.match.test(key)) ?? {
    layer: 'Cross-Layer',
    stage: 'Operational SQL',
  };
}

function inferBusinessPurpose({ title, practice, productionContext }) {
  const lower = `${title} ${practice} ${productionContext}`.toLowerCase();
  if (lower.includes('dedup')) return 'Deduplicate raw records before Silver and Gold loading.';
  if (lower.includes('cdc')) return 'Apply source changes safely without corrupting warehouse state.';
  if (lower.includes('scd')) return 'Preserve dimensional history for correct point-in-time reporting.';
  if (lower.includes('reconciliation')) return 'Prove source and target row counts agree before business users consume data.';
  if (lower.includes('partition') || lower.includes('pruning')) return 'Reduce scanned data and keep cloud warehouse spend predictable.';
  if (lower.includes('fact') || lower.includes('dimension') || lower.includes('star')) return 'Model trusted Gold data for BI, semantic models, and finance-grade reporting.';
  if (lower.includes('join')) return 'Combine fact and dimension data without changing the intended grain.';
  if (lower.includes('window') || lower.includes('row_number') || lower.includes('rank')) return 'Solve ordered analytics patterns such as deduplication, latest-state selection, and running metrics.';
  return 'Turn raw operational data into trusted, queryable pipeline outputs.';
}

function inferLessonInsights({ title, productionConcern, performanceWarning }) {
  const lower = title.toLowerCase();
  const isJoin = lower.includes('join');
  const isWindow = /row_number|rank|dense_rank|lag|lead|running|dedup/.test(lower);
  const isPerf = /index|partition|predicate|broadcast|plan|select \*|shuffle|optimization/.test(lower);
  const isModel = /fact|dimension|star|surrogate|grain|mart/.test(lower);

  return {
    productionMistakes: [
      productionConcern,
      isJoin && 'Joining tables before confirming grain and business key cardinality.',
      isWindow && 'Ranking records without a deterministic tie-breaker.',
      isModel && 'Letting dashboard-specific logic define the warehouse model.',
      isPerf && 'Optimizing only the SQL text instead of checking table layout and query plan.',
    ].filter(Boolean),
    optimizationTips: [
      performanceWarning,
      isJoin && 'Filter each side of the join before joining large warehouse tables.',
      isWindow && 'Partition windows by the business key and order by a deterministic timestamp or sequence.',
      isModel && 'Validate fact grain before adding measures or joining dimensions.',
      isPerf && 'Use EXPLAIN, partition filters, and column pruning before changing business logic.',
    ].filter(Boolean),
    costConsiderations: [
      isWindow && 'Window functions can trigger expensive sorts and shuffles on large Delta or warehouse tables.',
      isJoin && 'Many-to-many joins can multiply rows, increase shuffle, and inflate compute spend.',
      isPerf && 'Poor pruning and SELECT * patterns increase bytes scanned in Fabric, Synapse, and Databricks.',
    ].filter(Boolean),
    scalabilityConcerns: [
      isJoin && 'Small test joins can hide production fan-out when dimension keys are not unique.',
      isWindow && 'Unbounded windows over all history become slow as CDC and audit tables grow.',
      isModel && 'Gold models must keep stable grain as more reporting domains adopt them.',
    ].filter(Boolean),
    debuggingTips: [
      'Check row counts before and after each step.',
      isJoin && 'Compare key counts on each side of the join before blaming the dashboard.',
      isWindow && 'Inspect the top two rows per partition to verify the survivor rule.',
      isPerf && 'Read the query plan for scans, shuffles, sorts, and broadcast choices.',
    ].filter(Boolean),
  };
}

function inferVisualAids({ title, medallionLayer, pipelineStage }) {
  const lower = title.toLowerCase();
  const aids = [
    {
      title: 'Medallion placement',
      body: `${medallionLayer} layer · ${pipelineStage}. This lesson shows where the SQL pattern usually belongs in a production lakehouse.`,
    },
  ];
  if (/join/.test(lower)) {
    aids.push({
      title: 'Join data flow',
      body: 'Filter inputs → validate keys → join at the intended grain → reconcile row counts before publishing.',
      warning: 'Many-to-many joins can silently duplicate revenue.',
    });
  }
  if (/row_number|rank|dense_rank|lag|lead|running|window|dedup/.test(lower)) {
    aids.push({
      title: 'Window execution',
      body: 'Partition rows by business key, sort within each partition, then calculate rank, previous value, or running metric.',
      warning: 'Large partitions can create expensive distributed sorts.',
    });
  }
  if (/partition|pruning/.test(lower)) {
    aids.push({
      title: 'Partition pruning',
      body: 'Direct filters on partition columns let the engine skip irrelevant files or partitions.',
      warning: 'Wrapping partition columns in functions can disable pruning.',
    });
  }
  if (/group|having|aggregation|fact|mart/.test(lower)) {
    aids.push({
      title: 'Aggregation order',
      body: 'Filter rows first, group at the reporting grain, calculate measures, then filter groups with HAVING if needed.',
      warning: 'Adding extra dimensions changes the output grain.',
    });
  }
  if (/cte|subquer|temp/.test(lower)) {
    aids.push({
      title: 'Execution order',
      body: 'Break complex transformations into named steps: source filter, business rule, validation, final output.',
      warning: 'Repeated CTE references may be recomputed in some engines.',
    });
  }
  return aids;
}

function sqlLesson({
  id,
  title,
  difficulty = 'Intermediate',
  badges = DEFAULT_BADGES,
  dependsOn,
  what,
  why,
  syntax,
  example,
  expectedOutput,
  practice,
  hint,
  solution,
  azureRelevance,
  databricksRelevance,
  productionContext,
  productionConcern,
  commonMistake,
  performanceWarning,
  interviewQuestion,
  interviewAnswer,
  seniorUse,
  medallionLayer,
  pipelineStage,
  businessPurpose,
  productionMistakes,
  optimizationTips,
  costConsiderations,
  scalabilityConcerns,
  debuggingTips,
  visualAids,
  usageFrequency,
  completionOutcome,
}) {
  const inferred = inferLessonLayer(id, title);
  const resolvedLayer = medallionLayer ?? inferred.layer;
  const resolvedStage = pipelineStage ?? inferred.stage;
  const insights = inferLessonInsights({ title, productionConcern, performanceWarning });
  const resolvedBusinessPurpose = businessPurpose ?? inferBusinessPurpose({ title, practice, productionContext });
  const resolvedBadges = [
    ...new Set([
      ...badges,
      usageFrequency ?? 'High Usage',
      /scd|cdc|dedup|join|window|partition|performance|merge/i.test(`${id} ${title}`) ? 'Production Critical' : null,
      /interview critical|advanced|performance sensitive/i.test(badges.join(' ')) ? 'Most Asked in Interviews' : null,
      /null|distinct|left join|grain|scd|merge|partition/i.test(`${id} ${title}`) ? 'Commonly Misunderstood' : null,
    ].filter(Boolean)),
  ];
  return {
    id,
    title,
    difficulty,
    badges: resolvedBadges,
    dependsOn,
    medallionLayer: resolvedLayer,
    pipelineStage: resolvedStage,
    businessPurpose: resolvedBusinessPurpose,
    productionMistakes: productionMistakes ?? insights.productionMistakes,
    optimizationTips: optimizationTips ?? insights.optimizationTips,
    costConsiderations: costConsiderations ?? insights.costConsiderations,
    scalabilityConcerns: scalabilityConcerns ?? insights.scalabilityConcerns,
    debuggingTips: debuggingTips ?? insights.debuggingTips,
    visualAids: visualAids ?? inferVisualAids({ title, medallionLayer: resolvedLayer, pipelineStage: resolvedStage }),
    usageFrequency: usageFrequency ?? 'High',
    completionOutcome: completionOutcome ?? `After this lesson, learners can use ${title} in production Azure/Fabric/Databricks data engineering workflows.`,
    explanation: what,
    why,
    syntax,
    example,
    expectedOutput,
    practice,
    hint,
    solution,
    azureRelevance,
    databricksRelevance,
    productionContext,
    productionConcern,
    commonMistakes: [commonMistake],
    performanceTip: performanceWarning,
    seniorEngineerNote: seniorUse,
    interview: {
      question: interviewQuestion,
      answer: interviewAnswer,
    },
    hints: [
      hint,
      `Use the pattern: ${syntax}`,
      solution.split('\n').slice(0, 3).join('\n'),
      solution,
    ],
  };
}

